-- ticket-due-date (Emily, Nov 18). Adds a Due date to Operations tickets.
-- 1. tickets.due_on (nullable date).
-- 2. BEFORE INSERT trigger: when due_on is empty, Right now and Today get today (Central), Routine gets today + 7.
--    Set once at creation; a later priority change never touches it. Runs for every way a ticket is created.
-- 3. Open tickets that exist today (not resolved, not closed) get the same rule from the day they were created.
--    Resolved and closed tickets are not touched.
-- 4. Open tickets from the Notion import: the Due Date read once from each ticket's Notion page (Nov 18, read only,
--    nothing written to Notion) replaces that default. Pages with no Due Date keep the default. Source: notion-due-dates.csv.
-- 5. set_ticket_due_on: changes the date for anyone who can edit the ticket (caller's own access rules) and writes one
--    line to the ticket's history with the person who changed it. No reason needed.
-- The backfill runs with the import quiet setting (no alerts, no work item or owner updates) and without bumping
-- updated_at. One audit row ticket_due_date.apply. Undo: apply.undo.sql.

ALTER TABLE public.tickets ADD COLUMN due_on date;
COMMENT ON COLUMN public.tickets.due_on IS 'Due date (Central). Set once at creation from priority by tickets_zz_due_on_default; changed only through set_ticket_due_on.';

CREATE OR REPLACE FUNCTION private.ticket_due_on_default()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.due_on IS NULL THEN
    NEW.due_on := CASE lower(coalesce(NEW.priority, ''))
      WHEN 'p1' THEN (now() AT TIME ZONE 'America/Chicago')::date
      WHEN 'p2' THEN (now() AT TIME ZONE 'America/Chicago')::date
      WHEN 'p3' THEN (now() AT TIME ZONE 'America/Chicago')::date + 7
      ELSE NULL END;
  END IF;
  RETURN NEW;
END $function$;

-- Named to run after every other BEFORE INSERT rule on tickets, so it reads the final priority.
CREATE TRIGGER tickets_zz_due_on_default BEFORE INSERT ON public.tickets
  FOR EACH ROW EXECUTE FUNCTION private.ticket_due_on_default();

